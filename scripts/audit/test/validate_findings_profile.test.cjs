// Tests for scripts/audit/validate_findings_profile.cjs.
// Run: node --test scripts/audit/test/validate_findings_profile.test.cjs
//
// Fixtures are needs_validation findings built programmatically and
// written to a temporary directory per test. A finding whose trace is
// [entrypoint, composition, sink] produces exactly one vendored
// trace-ordering error, and that error is exempt under profile delta
// P3 (the wrapper filters it). The poison finding's validation_plan is
// the empty object {}: the profile schema requires no key inside
// validation_plan and "" would trip its minLength / visibleContent
// rules, so {} is the schema-valid shape that is semantically empty
// and must yield the vendored "requires at least one visible local or
// deployment plan" error.

"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const test = require("node:test");

const validatorPath = path.join(__dirname, "..", "validate_findings_profile.cjs");

function compositionFinding(index, { poison = false } = {}) {
  return {
    verdict: "needs_validation",
    fingerprint: `fp-${String(index).padStart(3, "0")}`,
    title: `Candidate ${index}`,
    description: `Candidate ${index} may reach an operation without a check.`,
    claimed_root_cause: `parse ${index} may pass an unbounded value onward.`,
    trace: [
      { kind: "entrypoint", file: "src/handler.c", line: 10, scope: "handle", description: "Attacker data enters." },
      { kind: "composition", file: "src/model.c", line: 20, scope: "compose", description: "Components compose here." },
      { kind: "sink", file: "src/store.c", line: 30, scope: "store", description: "The operation executes." },
    ],
    evidence: [
      { file: "src/handler.c", line: 10, description: "The source performs the operation without the required check." },
    ],
    blockers: ["no isolated environment available for dynamic validation"],
    validation_plan: poison
      ? {}
      : { local: "Run the smallest input that exceeds the documented limit and observe." },
  };
}

function plainFinding(index) {
  const finding = compositionFinding(index);
  finding.trace[1] = {
    kind: "propagation",
    file: "src/model.c",
    line: 20,
    scope: "propagate",
    description: "The value propagates onward.",
  };
  return finding;
}

function runValidator(findings) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "profile-validator-"));
  try {
    const file = path.join(dir, "findings.json");
    fs.writeFileSync(file, JSON.stringify(findings, null, 2));
    const result = spawnSync(process.execPath, [validatorPath, file], { encoding: "utf8" });
    return { status: result.status, output: `${result.stdout}${result.stderr}` };
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

test("composition errors saturating the vendored error cap cannot hide a later validation_plan error", () => {
  // 100 findings each contributing exactly one exempt composition
  // ordering error fill the vendored error list to its cap; the 101st
  // finding's non-exempt validation_plan error is never generated by
  // the capped pass and must still fail the document.
  const findings = Array.from({ length: 101 }, (_, i) =>
    compositionFinding(i, { poison: i === 100 })
  );
  const result = runValidator(findings);
  assert.notEqual(result.status, 0, `expected nonzero exit, got 0: ${result.output}`);
  assert.ok(
    result.output.includes(
      "$[100].validation_plan: requires at least one visible local or deployment plan"
    ),
    `expected failure output to name $[100].validation_plan, got: ${result.output}`
  );
});

test("100 composition findings with no other errors pass (control for the cap-saturation case)", () => {
  const findings = Array.from({ length: 100 }, (_, i) => compositionFinding(i));
  const result = runValidator(findings);
  assert.equal(result.status, 0, result.output);
  assert.match(result.output, /PASS/);
});

test("a small document with a composition trace and no other errors passes", () => {
  const result = runValidator([compositionFinding(0)]);
  assert.equal(result.status, 0, result.output);
  assert.match(result.output, /PASS/);
});

test("a small document with one composition finding and one ordinary non-exempt error fails", () => {
  const poisoned = plainFinding(1);
  poisoned.validation_plan = {};
  const result = runValidator([compositionFinding(0), poisoned]);
  assert.notEqual(result.status, 0, `expected nonzero exit, got 0: ${result.output}`);
  assert.ok(
    result.output.includes(
      "$[1].validation_plan: requires at least one visible local or deployment plan"
    ),
    `expected failure output to name $[1].validation_plan, got: ${result.output}`
  );
});
