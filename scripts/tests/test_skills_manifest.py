"""Tests for scripts/check_skills_manifest.py (Task F1).

unittest.TestCase style only: CI runs
``python3 -m unittest discover -s scripts/tests``.

Each test builds a temp fixture repo:

    <tmp>/repo/scripts/check_skills_manifest.py   (copied from the real script)
    <tmp>/repo/.github/skills-sync-scope.txt      (fixture scope, 3 fake skills)
    <tmp>/repo/.github/skills-manifest.sha256     (generated by --write)
    <tmp>/repo/skills/<skill>/...                 (fixture tree)

and drives the checker CLI via subprocess, so the checker's contract --
repo root resolved from the script's own location, never from --root or
CWD -- is exercised exactly as CI exercises it.
"""

import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
REAL_SCRIPT = REPO_ROOT / "scripts" / "check_skills_manifest.py"

FIXTURE_SCOPE = """\
# Fixture scope for test_skills_manifest.py.
[skills]
alpha
beta
scrubbing-public-tree

[exclude-paths]
skill.yaml
.superpowers/**
scrubbing-public-tree/SKILL.md

[exclude-content]
/home/hatch
"""


class SkillsManifestTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.base = Path(self._tmp.name)
        self.repo = self.base / "repo"
        (self.repo / "scripts").mkdir(parents=True)
        (self.repo / ".github").mkdir(parents=True)
        # Copying the real script is the point: in the RED phase the script
        # does not exist yet and every test fails here.
        shutil.copyfile(REAL_SCRIPT, self.repo / "scripts" / "check_skills_manifest.py")
        (self.repo / ".github" / "skills-sync-scope.txt").write_text(FIXTURE_SCOPE)
        self.skills = self.repo / "skills"
        self._write_file("alpha/SKILL.md", "alpha skill\n")
        self._write_file("alpha/guide.md", "alpha guide\n")
        self._write_file("beta/SKILL.md", "beta skill\n")
        self._write_file("scrubbing-public-tree/LICENSE", "license text\n")

    # -- helpers ---------------------------------------------------------

    def _write_file(self, rel, text):
        path = self.skills / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return path

    def _run(self, repo, mode):
        return subprocess.run(
            [
                sys.executable,
                str(repo / "scripts" / "check_skills_manifest.py"),
                "--root",
                str(repo / "skills"),
                mode,
            ],
            capture_output=True,
            text=True,
            # CWD deliberately outside the fixture repo: the checker must
            # resolve its repo root from its own location, never from CWD.
            cwd=str(self.base),
        )

    def _write_manifest(self, repo=None):
        repo = repo or self.repo
        proc = self._run(repo, "--write")
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        return proc

    def _check(self, repo=None):
        return self._run(repo or self.repo, "--check")

    def _manifest_text(self, repo=None):
        repo = repo or self.repo
        return (repo / ".github" / "skills-manifest.sha256").read_text()

    # -- cases (a)-(g) from the plan, plus the --write content rule ------

    def test_a_tree_matches_manifest_exits_zero(self):
        self._write_manifest()
        proc = self._check()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

    def test_b_one_byte_differs_exits_one_and_names_file(self):
        self._write_manifest()
        target = self.skills / "alpha" / "guide.md"
        data = bytearray(target.read_bytes())
        data[0] ^= 0x01
        target.write_bytes(bytes(data))
        proc = self._check()
        self.assertEqual(proc.returncode, 1, proc.stdout + proc.stderr)
        self.assertIn("alpha/guide.md", proc.stdout + proc.stderr)

    def test_c_unlisted_in_scope_file_exits_one(self):
        self._write_manifest()
        self._write_file("beta/extra.txt", "unlisted\n")
        proc = self._check()
        self.assertEqual(proc.returncode, 1, proc.stdout + proc.stderr)
        self.assertIn("beta/extra.txt", proc.stdout + proc.stderr)

    def test_d_listed_file_missing_exits_one(self):
        self._write_manifest()
        (self.skills / "alpha" / "SKILL.md").unlink()
        proc = self._check()
        self.assertEqual(proc.returncode, 1, proc.stdout + proc.stderr)
        self.assertIn("alpha/SKILL.md", proc.stdout + proc.stderr)

    def test_e_excluded_paths_never_flagged(self):
        # Excluded paths present at generation time: never in the manifest.
        self._write_file("alpha/skill.yaml", "name: alpha\n")
        self._write_file("beta/.superpowers/state.txt", "scratch\n")
        self._write_file("scrubbing-public-tree/SKILL.md", "excluded copy\n")
        self._write_manifest()
        manifest = self._manifest_text()
        self.assertNotIn("skill.yaml", manifest)
        self.assertNotIn(".superpowers", manifest)
        self.assertNotIn("scrubbing-public-tree/SKILL.md", manifest)
        self.assertIn("scrubbing-public-tree/LICENSE", manifest)
        # Present -> check passes.
        proc = self._check()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        # Absent -> check still passes (never flagged either way).
        (self.skills / "alpha" / "skill.yaml").unlink()
        shutil.rmtree(self.skills / "beta" / ".superpowers")
        (self.skills / "scrubbing-public-tree" / "SKILL.md").unlink()
        proc = self._check()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

    def test_f_write_then_check_round_trip_across_roots(self):
        self._write_manifest()
        moved = self.base / "elsewhere" / "repo-copy"
        moved.parent.mkdir(parents=True)
        shutil.copytree(self.repo, moved)
        proc = self._check(repo=moved)
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

    def test_g_listed_file_gaining_content_literal_is_stale_entry(self):
        self._write_manifest()
        target = self.skills / "beta" / "SKILL.md"
        target.write_text(target.read_text() + "see /home/hatch for details\n")
        proc = self._check()
        self.assertEqual(proc.returncode, 1, proc.stdout + proc.stderr)
        output = proc.stdout + proc.stderr
        self.assertIn("beta/SKILL.md", output)
        self.assertIn("stale manifest entry", output)

    def test_h_write_excludes_content_rule_files_and_reports_them(self):
        self._write_file("alpha/local-paths.md", "generated under /home/hatch\n")
        proc = self._write_manifest()
        self.assertIn(
            "excluded (content rule): alpha/local-paths.md",
            proc.stdout + proc.stderr,
        )
        self.assertNotIn("local-paths", self._manifest_text())
        # Pinned check semantics: the content rule does NOT apply to
        # unlisted files at check time -- an unlisted in-scope file is
        # flagged whatever its contents. So a tree still carrying the
        # generation-excluded file is flagged by --check as unlisted;
        # that surfacing is the contract, not a checker bug.
        proc = self._check()
        self.assertEqual(proc.returncode, 1, proc.stdout + proc.stderr)
        self.assertIn("alpha/local-paths.md", proc.stdout + proc.stderr)


if __name__ == "__main__":
    unittest.main()
